import {cp,mkdir,writeFile,readFile,readdir} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
import {modelRuntimeStatus,installModelRuntime} from '../../dist/library/model-runtime-install.js';
import {modelRuntime} from '../../dist/library/model-runtime.js';
const cache=path.resolve('.avid-mcp-analysis/models');
const before=await modelRuntimeStatus(cache);assert.ok(before.managed&&before.unchanged);
const root=path.resolve('.avid-mcp-analysis',`runtime-receipt-${randomUUID()}`);await mkdir(root);
const source=path.join(cache,'runtime'),destination=path.join(root,'runtime');
await cp(source,destination,{recursive:true,force:false,errorOnExist:true,filter:entry=>entry!==path.join(source,'installation.json')});
const abandoned=path.join(root,`.runtime-receipt-${randomUUID()}.tmp`);await writeFile(abandoned,'{interrupted',{flag:'wx'});
assert.equal((await modelRuntimeStatus(root)).managed,false);
const adopted=await installModelRuntime(root);assert.ok(adopted.managed&&adopted.unchanged&&adopted.reused&&adopted.receipt.adoptedLegacy);
assert.equal(adopted.treeSha256,before.treeSha256);assert.equal(await readFile(abandoned,'utf8'),'{interrupted');
const temporary=(await readdir(root)).filter(n=>n.startsWith('.runtime-receipt-'));assert.deepEqual(temporary,[path.basename(abandoned)]);
const loaded=await modelRuntime(root);assert.deepEqual(new loaded.Tensor('float32',new Float32Array([1,2]),[2]).dims,[2]);
const after=await modelRuntimeStatus(cache);assert.ok(after.managed&&after.unchanged);assert.equal(after.treeSha256,before.treeSha256);
await writeFile(path.join(root,'evidence.json'),JSON.stringify({adopted,originalTreeUnchanged:true,abandonedTemporaryPreserved:true,runtimeImportPassed:true,limitations:['Disposable copy adoption, not a power-loss simulation','No model inference or automatic stale-lock recovery','Temporary receipt is outside the inventoried dependency tree']},null,2),{flag:'wx'});
console.log(JSON.stringify({root,passed:true,treeSha256:adopted.treeSha256}));
