import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
import {runProcess} from '../../dist/process.js';
import {sha256File} from '../../dist/analysis/file-inventory.js';

const root=path.resolve('.avid-mcp-analysis',`installed-native-${randomUUID()}`);await mkdir(root);
const run=async args=>{const result=await runProcess(process.execPath,args,{timeoutMs:300000,maxOutputBytes:4*1024*1024});assert.equal(result.exitCode,0,result.stderr);return result.stdout;};
const npm=path.join(path.dirname(process.execPath),'node_modules/npm/bin/npm-cli.js');
const packed=JSON.parse(await run([npm,'pack','--json','--ignore-scripts','--pack-destination',root]));
assert.equal(path.basename(packed[0].filename),packed[0].filename);
const archive=path.join(root,packed[0].filename),archiveSha256=await sha256File(archive);
const installation=JSON.parse(await run(['dist/cli.js','--package-install',archive,'--package-root',path.join(root,'packages'),'--package-sha256',archiveSha256]));
const native=JSON.parse(await run(['scripts/research/qualify-native-reopen.mjs',path.resolve('.venv',process.platform==='win32'?'Scripts/python.exe':'bin/python'),installation.entry,installation.entrySha256]));
const nativeEvidence=JSON.parse(await readFile(native.evidence,'utf8'));
assert.equal(nativeEvidence.serverEntry,installation.entry);
assert.equal(nativeEvidence.serverEntrySha256,installation.entrySha256);
assert.equal(nativeEvidence.savedTimelineVerified,true);
const columns=JSON.parse(await run(['scripts/research/qualify-native-bin-columns.mjs',installation.entry,installation.entrySha256]));
const columnEvidence=JSON.parse(await readFile(columns.evidence,'utf8'));
assert.equal(columnEvidence.serverEntry,installation.entry);
assert.equal(columnEvidence.serverEntrySha256,installation.entrySha256);
assert.equal(columnEvidence.reconnected,true);
assert.equal(columnEvidence.unchanged,true);
assert.equal(await sha256File(installation.entry),installation.entrySha256);
assert.equal(await sha256File(archive),archiveSha256);
await writeFile(path.join(root,'evidence.json'),JSON.stringify({ok:true,checkedAt:new Date().toISOString(),installation,archive,archiveSha256,nativeEvidence:native.evidence,columnEvidence:columns.evidence,limitations:'Fresh managed-package native reads and bin-column reconnect against the existing qualified Windows host. Independent saved-bin oracle uses checkout Python scripts and existing virtual environment. No clean-machine dependency setup, GUI/model invocation, native write or render claim.'},null,2));
console.log(JSON.stringify({ok:true,root,nativeEvidence:native.evidence,columnEvidence:columns.evidence}));
