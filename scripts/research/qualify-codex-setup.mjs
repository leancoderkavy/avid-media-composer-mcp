import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import path from 'node:path';
import assert from 'node:assert/strict';
const binary=process.argv[2];assert.ok(binary&&path.isAbsolute(binary));
const root=path.resolve('.avid-mcp-analysis',`codex-setup-${randomUUID()}`),configuration=path.join(root,'configuration'),project=path.join(root,'fixture space $literal & value');
await mkdir(configuration,{recursive:true});await mkdir(project);
const run=(command,args,extra={})=>{const result=spawnSync(command,args,{cwd:project,windowsHide:true,encoding:'utf8',timeout:30000,...extra});if(result.error)throw result.error;assert.equal(result.status,0,result.stderr);return result.stdout;};
const generated=JSON.parse(run(process.execPath,[path.resolve('dist/cli.js'),'--client','codex','--root',project,'--capabilities','inspect']));
assert.equal(generated.command,'codex');
const env={...process.env,CODEX_HOME:configuration};
run(binary,generated.args,{env});
const configured=JSON.parse(run(binary,['mcp','get','avid-media-composer','--json'],{env}));
assert.equal(configured.transport.command,process.execPath);
assert.deepEqual(configured.transport.args,[path.resolve('dist/index.js')]);
assert.equal(configured.transport.env.AVID_MCP_ALLOWED_ROOTS,project);assert.equal(configured.transport.env.AVID_MCP_CAPABILITIES,'inspect');
const saved=await readFile(path.join(configuration,'config.toml'),'utf8');assert.ok(saved.includes('avid-media-composer'));
run(binary,['mcp','remove','avid-media-composer'],{env});
assert.ok(!(await readFile(path.join(configuration,'config.toml'),'utf8')).includes('avid-media-composer'));
await writeFile(path.join(root,'evidence.json'),JSON.stringify({generated,configured,removed:true,scope:'Actual generated-command install/readback/removal in an isolated Codex home. Existing authenticated model invocation is separately qualified; no user configuration touched.'},null,2),{flag:'wx'});
console.log(JSON.stringify({root,passed:true}));
