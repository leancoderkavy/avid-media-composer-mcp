import {mkdir,writeFile,readdir} from 'node:fs/promises';
import path from 'node:path';
import {MediaLibrary} from '../../dist/library/media-library.js';
import {loadConfig} from '../../dist/config.js';
const directory=path.resolve('.avid-mcp-analysis/sonoma-library-20260905');
await mkdir(directory,{recursive:true});
const library=new MediaLibrary(loadConfig({AVID_MCP_ALLOWED_ROOTS:'D:/Sonoma Escape Edit',AVID_MCP_OUTPUT_ROOT:directory,AVID_MCP_CAPABILITIES:'inspect,export,project-write',AVID_MCP_COMMAND_TIMEOUT_MS:'120000'}));
const files=(await readdir('D:/Sonoma Escape Edit')).filter(file=>file.endsWith('.mp4')).map(file=>path.join('D:/Sonoma Escape Edit',file));
const index=await library.index(files);
const preview=index.entries.find(entry=>entry.file.endsWith('v1_preview.mp4'));
if(!preview)throw new Error('Preview fixture missing');
const thumbnail=await library.artifact(preview.id,'thumbnail',95);
const clip=await library.artifact(preview.id,'clip',95,97);
const copy=await library.artifact(preview.id,'copy');
const report=await library.report(index.entries.map(entry=>entry.id));
const search=await library.search(index.entries.map(entry=>entry.id),'h264');
if(search.results.length!==7)throw new Error('Expected seven indexed H264 files');
await writeFile(path.join(directory,'results.json'),JSON.stringify({index,thumbnail,clip,copy,report,search},null,2));
console.log(JSON.stringify({indexed:index.entries.length,thumbnail,clip,copy,report,metadataMatches:search.results.length}));
