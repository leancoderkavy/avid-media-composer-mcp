import {MediaLibrary} from '../../dist/library/media-library.js';
import {AnalysisJobs} from '../../dist/library/jobs.js';
import {loadConfig} from '../../dist/config.js';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const output=path.resolve('.avid-mcp-analysis/sonoma-library-20260905');
const config=loadConfig({AVID_MCP_ALLOWED_ROOTS:'D:/Sonoma Escape Edit',AVID_MCP_OUTPUT_ROOT:output,AVID_MCP_CAPABILITIES:'inspect,export,project-write',AVID_MCP_COMMAND_TIMEOUT_MS:'120000'});
const library=new MediaLibrary(config);
const prior=JSON.parse(await readFile(path.join(output,'results.json'),'utf8'));
const ids=prior.index.entries.map(entry=>entry.id);
const facets=await library.facets(ids);
assert.equal(facets.facets.codec.h264,7);
const speech=JSON.parse(await readFile(path.join(output,'speech-results.json'),'utf8'));
console.log('speech evidence keys',Object.keys(speech));
const revision=speech.revision;
assert.equal(typeof revision,'string');
const exports=[];
for(const format of ['txt','json','csv','srt','vtt'])exports.push(await library.exportTranscript(prior.thumbnail.id,revision,format));
const outline=await library.outline(prior.thumbnail.id,revision,30);
const sheet=await library.contactSheet(ids);
const jobs=new AnalysisJobs(config);
const running=await jobs.start({kind:'index',files:[prior.index.entries[0].file]});
const queued=await jobs.start({kind:'index',files:[prior.index.entries[1].file]});
assert.equal(jobs.cancel(queued.id).status,'cancelled');
const deadline=Date.now()+120000;
while(['queued','running'].includes(jobs.status(running.id).status)&&Date.now()<deadline)await new Promise(resolve=>setTimeout(resolve,200));
assert.equal(jobs.status(running.id).status,'completed');
const cancelled=await jobs.start({kind:'artifact',id:prior.thumbnail.id,format:'clip',start:0,end:180});
assert.ok(['cancelling','cancelled'].includes(jobs.cancel(cancelled.id).status));
const stopDeadline=Date.now()+30000;
while(jobs.status(cancelled.id).status==='cancelling'&&Date.now()<stopDeadline)await new Promise(resolve=>setTimeout(resolve,100));
assert.equal(jobs.status(cancelled.id).status,'cancelled');
jobs.close();
const result={facets,exports,outline,sheet,jobs:[jobs.status(running.id),jobs.status(queued.id),jobs.status(cancelled.id)]};
await writeFile(path.join(output,'extras-results.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify({passed:true,files:ids.length,exports:exports.length,sheet,jobs:result.jobs.map(job=>job.status)}));
