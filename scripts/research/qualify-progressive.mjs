import {NativeAdapter} from '../../dist/native/adapter.js';
import {loadConfig} from '../../dist/config.js';
import {readdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const projectPath='D:/Avid Projects/MCP_Sonoma_30p_20260905';
const adapter=new NativeAdapter(loadConfig({AVID_MCP_NATIVE_BINARY:'C:/Program Files/Avid/Avid Media Composer/AvidMediaComposer.exe',AVID_MCP_ALLOWED_ROOTS:projectPath+';D:/Sonoma Escape Edit',AVID_MCP_CAPABILITIES:'inspect,edit,project-write'}));
const evidence=[];
const record=async(name,run)=>{const result=await run();evidence.push({name,result});await writeFile('.avid-mcp-analysis/progressive-qualification.json',JSON.stringify(evidence,null,2));console.log(name);return result;};
const action=async operation=>{const preview=await adapter.preview(operation);return record(operation.action,()=>adapter.apply(preview.token));};
const project=await record('project',()=>adapter.project());
if(path.resolve(project.path)!==path.resolve(projectPath)||project.frame_rate?.num!==30||project.frame_rate?.den!==1)throw new Error('Expected disposable 30 fps project: '+JSON.stringify(project));
const bin='MCP_Sonoma_Media.avb';
await action({action:'create_bin',name:'MCP_Sonoma_Media'});
const files=(await readdir('D:/Sonoma Escape Edit')).filter(file=>file.endsWith('.mp4'));
for(const file of files)await action({action:'link_media',bin,media:path.join('D:/Sonoma Escape Edit',file)});
const before=await record('clips-before-close',()=>adapter.read('clips',bin));
if(before.length!==7)throw new Error('Expected seven clips');
await action({action:'close_bin',bin});
await action({action:'open_bin',bin});
const after=await record('clips-after-reopen',()=>adapter.read('clips',bin));
if(JSON.stringify(before)!==JSON.stringify(after))throw new Error('Clip persistence mismatch');
console.log(JSON.stringify({passed:true,clips:after.length}));
